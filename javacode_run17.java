// How is our Code Running?
// Source Code → Compiler → Byte Code → JVM (Java Virtual Machine) → Native Code
// - Source Code → .java
// - Byte Code → .class
// - JVM → Java Virtual Machine
// - Compilation: Source Code → Byte Code
// - Execution: Byte Code → JVM → Native Code


// First, we write the source code in a .java file.
// Second, the compiler compiles the source code and converts it into bytecode, which is stored in a .class file.
// Third, the JVM (Java Virtual Machine) takes the bytecode and converts it into machine/native code that the computer can execute.