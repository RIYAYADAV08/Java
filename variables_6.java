//Variables
//A variable is a named memory location used to store a value. A variable's value can be changed.
//Its syntax is dataType variableName = value;         //; called statement terminator

public class variables_6 {
    public static void main(String args[]) {
        int a = 21;
        int b = 40;

        System.out.println(a);
        System.out.println(b);

        a = 30;
        System.out.println(a);
        a = b; // b ki value jake a me store ho gyi.
        System.out.println(a);
        String name = "Riya";
        System.out.println(name);
    }
}
