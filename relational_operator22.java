//Relational operators are used to compare two values and return a boolean value (true or false).

public class relational_operator22 {
    public static void main(String args[]) {
        int a = 10;
        int b = 20;

        System.out.println(a > b);
        System.out.println(a < b);
        System.out.println(a >= b);
        System.out.println(a <= b);
        System.out.println(a == b);
        System.out.println(a != b);
    }
}
